function cachePath(): string
{
    return app()->bootstrapPath('cache/laravents.php');
}

/**
 * A directory with no classes in it, for laravents.paths.
 *
 * @return list<string>
 */
function emptyPaths(): array
{
    $path = sys_get_temp_dir().'/laravents-empty';

    if (! is_dir($path)) {
        mkdir($path);
    }

    return [$path];
}

/** A registry resolved as the next boot would: the singleton forgotten, so the provider's closure runs again. */
function freshRegistry(): Registry
{
    app()->forgetInstance(Registry::class);

    return app(Registry::class);
}

test('a registry read back from its plain data answers as it was built, pointcut attribute instances included', function (): void {
    $built = (new RegistryBuilder('Laravents\Tests\Fixtures\Interception'))->build([
        LabHandlers::class,
        AuditedHandlers::class,
        DeadlockHandlers::class,
        HappenedListeners::class,
        LabInterceptors::class,
    ]);

    $data = $built->toArray();
    $restored = Registry::fromArray($data, LaraventsServiceProvider::manifests(app()));

    // Plain data only: what var_export() writes as PHP and opcache keeps as it is.
    array_walk_recursive($data, static fn (mixed $value) => expect($value === null || is_scalar($value))->toBeTrue());

    expect($restored->all())->toEqual($built->all())
        ->and($restored->fromCache())->toBeTrue()
        ->and($built->fromCache())->toBeFalse();

    foreach ($built->all() as $handler) {
        expect($restored->interceptorsFor($handler))->toEqual($built->interceptorsFor($handler));
    }

    $look = $restored->queryHandler('lab.look');
    expect($look)->not->toBeNull();

    $limits = array_values(array_filter(
        $restored->interceptorsFor($look),
        static fn (AppliedInterceptor $applied): bool => $applied->attribute instanceof Limited,
    ));

    expect($limits)->toHaveCount(1)
        ->and($limits[0]->attribute)->toEqual(new Limited(max: 3));

    $attribute = $limits[0]->attribute;
    expect($attribute instanceof Limited ? $attribute->max : null)->toBe(3);
});

test('laravents:cache writes one plain PHP array the next boot loads instead of scanning', function (): void {
    expect(Artisan::call('laravents:cache'))->toBe(0)
        ->and(Artisan::output())->toContain('Laravents registry cached successfully.')
        ->and(cachePath())->toBeFile();

    $file = include cachePath();

    expect(file_get_contents(cachePath()))->toStartWith("<?php\n\n// Generated by laravents:cache.")->not->toContain('unserialize');
    expect($file)->toMatchShape('array{format: 2, fingerprint: non-empty-string, registry: array{handlers: list<list<scalar|null>>, commands: array<string, int>, queries: array<string, int>, interceptors: list<list<scalar>>, interceptorsByHandler: array<string, list<array{int, bool|array{class-string, array<array-key, scalar|array<array-key, mixed>|null>}}>>, rootNamespace: non-empty-string, modules: list<array{string, string, bool, array{class-string, array<string, mixed>}|null}>}}');
    expect($file['fingerprint'])->toBe(RegistryCache::fingerprint(config(), app()->basePath()))
        ->and(glob(cachePath().'*'))->toBe([cachePath()]);

    $registry = freshRegistry();

    expect($registry->fromCache())->toBeTrue()
        ->and($registry->commandHandler('band.give_nickname')?->handler())->toBe('Modules\Band\Handlers\BandHandlers@give');
});

test('a cache written for another configuration is set aside: the registry is scanned and the log says so once', function (): void {
    Artisan::call('laravents:cache');
    config(['laravents.paths' => emptyPaths()]);
    $log = Log::spy();

    $registry = freshRegistry();
    freshRegistry();

    expect($registry->fromCache())->toBeFalse()
        ->and($registry->all())->toBe([]);

    $log->shouldHaveReceived('warning')->once()->withArgs(static fn (string $message): bool => str_contains($message, 'was written for another configuration'));
});

test('a module disabled after laravents:cache is out at once', function (): void {
