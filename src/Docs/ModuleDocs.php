<?php

declare(strict_types=1);

namespace Laravents\Docs;

use Laravents\Discovery\ModuleCanvas;

/**
 * The module canvases as Markdown, for a repository to link to and GitHub to render: an index with the module list
 * and a Mermaid dependency graph, and one page per module with the canvas as tables. The output depends only on the
 * canvases (no timestamps, stable order), so generating twice gives the same bytes.
 *
 * @phpstan-import-type Canvas from ModuleCanvas
 * @phpstan-import-type Handled from ModuleCanvas
 */
final class ModuleDocs
{
    private const string GENERATED = '<!-- Generated by php artisan laravents:docs. Do not edit; run it again instead. -->';

    /** @param list<Canvas> $canvases */
    public static function index(array $canvases): string
    {
        $lines = [self::GENERATED, '', '# Modules', ''];

        $lines = [...$lines, ...self::table(
            ['Module', 'Namespace', 'Commands', 'Queries', 'Events published', 'Events consumed', 'Depends on'],
            array_map(static fn (array $canvas): array => [
                sprintf('[%s](%s.md)', $canvas['module'], $canvas['module']),
                self::code($canvas['namespace']),
                (string) count($canvas['commands']),
                (string) count($canvas['queries']),
                (string) count($canvas['events_published']),
                (string) count($canvas['events_consumed']),
                self::list(array_map(static fn (array $dependency): string => $dependency['module'], $canvas['depends_on'])),
            ], $canvases),
        )];

        $lines = [...$lines, '', '## Dependencies', '', ...self::graph($canvases)];

        return implode("\n", $lines)."\n";
    }

    /** @param Canvas $canvas */
    public static function page(array $canvas): string
    {
        $published = [];
        $publications = [];

        foreach ($canvas['events_published'] as $event) {
            foreach ($event['listeners'] === [] ? [null] : $event['listeners'] as $listener) {
                $published[] = [
                    self::code($event['event']),
                    $listener === null ? '-' : self::code($listener['handler']),
                    $listener['module'] ?? '-',
                    $listener['mode'] ?? '-',
                    $listener['queue'] ?? '-',
                ];
            }

            foreach ($event['from'] as $publication) {
                $publications[] = [self::code($event['event']), self::code($publication['model']), $publication['hook']];
            }
        }

        $endpoints = array_values(array_filter(array_map(
            static fn (array $handled): ?array => $handled['http'] === null ? null : [self::code($handled['http']), self::code($handled['handler'])],
            [...$canvas['commands'], ...$canvas['queries']],
        )));

        $lines = [
            self::GENERATED,
            '',
            '# '.$canvas['module'],
            '',
            sprintf('Namespace %s. [All modules](README.md)', self::code($canvas['namespace'])),
            ...self::section('Commands', self::handledTable($canvas['commands'])),
            ...self::section('Queries', self::handledTable($canvas['queries'])),
            ...self::section('Events published', $published === [] ? [] : self::table(['Event', 'Listener', 'Module', 'Mode', 'Queue'], $published)),
            ...self::section('Events consumed', $canvas['events_consumed'] === [] ? [] : self::table(
                ['Event', 'Handler', 'From', 'Mode', 'Queue'],
                array_map(static fn (array $event): array => [
                    self::code($event['event']),
                    self::code($event['handler']),
                    $event['module'],
                    $event['mode'],
                    $event['queue'] ?? '-',
                ], $canvas['events_consumed']),
            )),
            ...self::section('Model publications', $publications === [] ? [] : self::table(['Event', 'Model', 'On'], $publications)),
            ...self::section('HTTP endpoints', $endpoints === [] ? [] : self::table(['Endpoint', 'Handler'], $endpoints)),
            ...self::section('Dependencies', $canvas['depends_on'] === [] ? [] : self::table(
                ['Module', 'Classes', 'Outside Api'],
                array_map(static fn (array $dependency): array => [
                    sprintf('[%s](%s.md)', $dependency['module'], $dependency['module']),
                    (string) $dependency['classes'],
                    (string) $dependency['outside_api'],
                ], $canvas['depends_on']),
            )),
        ];

        return implode("\n", $lines)."\n";
    }

    /**
     * graph LR with one edge per module dependency; an edge with references outside the target's Api, which
     * laravents:verify reports as direction violations, is dashed and labelled with their count.
     *
     * @param  list<Canvas>  $canvases
     * @return list<string>
     */
    private static function graph(array $canvases): array
    {
        $lines = ['```mermaid', 'graph LR'];
        $dashed = false;
        $connected = [];

        foreach ($canvases as $canvas) {
            foreach ($canvas['depends_on'] as $dependency) {
                $connected[$canvas['module']] = $connected[$dependency['module']] = true;
            }
        }

        foreach ($canvases as $canvas) {
            // A module with no edge would not appear in the graph otherwise.
            if (! isset($connected[$canvas['module']])) {
                $lines[] = '    '.self::node($canvas['module']);
            }

            foreach ($canvas['depends_on'] as $dependency) {
                if ($dependency['outside_api'] === 0) {
                    $lines[] = sprintf('    %s --> %s', self::node($canvas['module']), self::node($dependency['module']));
                } else {
                    $dashed = true;
                    $lines[] = sprintf('    %s -. "%d outside Api" .-> %s', self::node($canvas['module']), $dependency['outside_api'], self::node($dependency['module']));
                }
            }
        }

        $lines[] = '```';

        if ($dashed) {
            return [...$lines, '', 'A dashed edge reaches outside the other module\'s Api: `php artisan laravents:verify` reports it as a direction violation.'];
        }

        return $lines;
    }

    /**
     * @param  list<Handled>  $handled
     * @return list<string>
     */
    private static function handledTable(array $handled): array
    {
        return $handled === [] ? [] : self::table(
            ['Routing key', 'Handler', 'Message', 'Interceptors', 'HTTP'],
            array_map(static fn (array $row): array => [
                self::code($row['routing_key'] ?? '-'),
                self::code($row['handler']),
                $row['message'] === null ? '-' : self::code($row['message']),
                self::list($row['interceptors']),
                $row['http'] === null ? '-' : self::code($row['http']),
            ], $handled),
        );
    }

    /**
     * @param  list<string>  $body
     * @return list<string>
     */
    private static function section(string $title, array $body): array
    {
        return ['', '## '.$title, '', ...($body === [] ? ['None.'] : $body)];
    }

    /**
     * @param  list<string>  $header
     * @param  list<list<string>>  $rows
     * @return list<string>
     */
    private static function table(array $header, array $rows): array
    {
        return [self::row($header), '|'.str_repeat('---|', count($header)), ...array_map(self::row(...), $rows)];
    }

    /** @param list<string> $cells */
    private static function row(array $cells): string
    {
        return '| '.implode(' | ', str_replace('|', '\|', $cells)).' |';
    }

    private static function code(string $text): string
    {
        return '`'.$text.'`';
    }

    /** @param list<string> $items */
    private static function list(array $items): string
    {
        return $items === [] ? '-' : implode(', ', $items);
    }

    /** A Mermaid node id: a module name is a PHP namespace segment, so it is already a safe identifier. */
    private static function node(string $module): string
    {
        return $module;
    }
}
