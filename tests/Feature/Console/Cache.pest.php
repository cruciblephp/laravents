test('a pointcut attribute is cached as its class and source arguments when they are plain data, else rebuilt through reflection', function (): void {
    $built = (new RegistryBuilder('Laravents\Tests\Fixtures\Interception'))->build([
        LabHandlers::class,
        TieredHandlers::class,
        LabInterceptors::class,
        TieredInterceptors::class,
    ]);

    $data = $built->toArray();
    $rows = $data['interceptorsByHandler'];

    expect($rows[LabHandlers::class.'@look'][0][1])->toBe([Limited::class, ['max' => 3]])
        ->and($rows[TieredHandlers::class.'@tiered'][0][1])->toBeTrue();

    $restored = Registry::fromArray($data, LaraventsServiceProvider::manifests(app()));
    $tiered = $restored->commandHandler('lab.tiered');
    expect($tiered)->not->toBeNull();

    expect($restored->interceptorsFor($tiered)[0]->attribute)->toEqual(new Tiered(Tier::Gold));
});

test('write makes the directory the cache needs, and says so when it cannot', function (): void {
    $directory = storage_path('framework/testing/laravents-'.bin2hex(random_bytes(4)));
    $nested = new RegistryCache($directory.'/nested/laravents.php');
    $nested->write(LaraventsServiceProvider::scan(config()), 'fingerprint');

    expect($nested->path)->toBeFile();
    (new Filesystem)->deleteDirectory($directory);

    $file = (string) tempnam(sys_get_temp_dir(), 'laravents');

    expect(static fn () => (new RegistryCache($file.'/laravents.php'))->write(LaraventsServiceProvider::scan(config()), 'fingerprint'))
        ->toThrow(RuntimeException::class, 'its directory cannot be made');
    unlink($file);
});

test('a write that fails throws, leaves the cache as it was and nothing beside it', function (): void {
    $directory = storage_path('framework/testing/laravents-'.bin2hex(random_bytes(4)));
    mkdir($directory, 0755, true);
    // A name the file system takes, while the one beside it, written first, is longer than a name may be.
    $cache = new RegistryCache($directory.'/'.str_repeat('c', 236).'.php');
    file_put_contents($cache->path, "<?php\n\nreturn [];\n");

    expect(static fn () => $cache->write(LaraventsServiceProvider::scan(config()), 'fingerprint'))
        ->toThrow(RuntimeException::class, 'cannot be written')
        ->and(file_get_contents($cache->path))->toBe("<?php\n\nreturn [];\n")
        ->and(scandir($directory))->toBe(['.', '..', basename($cache->path)]);

    (new Filesystem)->deleteDirectory($directory);
});

test('a rename that fails throws and removes the file it wrote beside the cache', function (): void {
    $directory = storage_path('framework/testing/laravents-'.bin2hex(random_bytes(4)));
    // A directory with something in it where the cache file goes: no file can be renamed over it.
    mkdir($directory.'/laravents.php/taken', 0755, true);

    expect(static fn () => (new RegistryCache($directory.'/laravents.php'))->write(LaraventsServiceProvider::scan(config()), 'fingerprint'))
        ->toThrow(RuntimeException::class, 'cannot be written')
        ->and(scandir($directory))->toBe(['.', '..', 'laravents.php']);

    (new Filesystem)->deleteDirectory($directory);
});

