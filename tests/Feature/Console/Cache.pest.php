test('clear says so when the file is there and cannot be removed', function (): void {
    $directory = storage_path('framework/testing/laravents-'.bin2hex(random_bytes(4)));
    mkdir($directory, 0755, true);
    $cache = new RegistryCache($directory.'/laravents.php');
    $cache->write(LaraventsServiceProvider::scan(config()), 'fingerprint');
    chmod($directory, 0555);

    try {
        expect(static fn () => $cache->clear())->toThrow(RuntimeException::class, 'cannot be removed')
            ->and($cache->path)->toBeFile();
    } finally {
        chmod($directory, 0755);
        (new Filesystem)->deleteDirectory($directory);
    }
})->skip(static fn (): bool => function_exists('posix_geteuid') && posix_geteuid() === 0, 'root removes a file from a read-only directory');

